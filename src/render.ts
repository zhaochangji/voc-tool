/**
 * 报告生成器：report.json（双语）+ 源评论数据 → report.html（单文件网页，中/EN 一键切换）
 * 用法：
 *   npm run render -- sample-data/real-B00CPDWT2M.json
 *   # 需先跑过 analyze（report.json 含 {report:{zh,en}, themes:{zh,en}}）
 */
import { readFileSync, writeFileSync } from 'node:fs';

const srcPath = process.argv[2];
if (!srcPath) throw new Error('用法: npm run render -- sample-data/real-XXXX.json');

type ReportBody = {
    executive_summary: string;
    top_strengths: { theme: string; frequency: number }[];
    top_risks: { theme: string; frequency: number }[];
    buyer_personas: string[];
    listing_rewrite_checklist: string[];
    verdict: string;
};
type Theme = {
    kind: 'strength' | 'risk';
    theme: string;
    frequency: number;
    severity_avg: number;
    sample_seqs: number[];
    root_cause: string;
    listing_action: string;
};
type Loaded = {
    meta: { model: string; reviewCount: number; cost_usd: number; langs: string[] };
    report: { zh: ReportBody; en: ReportBody };
    themes: { zh: Theme[]; en: Theme[] };
};

const report: Loaded = JSON.parse(readFileSync('report.json', 'utf-8'));
const srcRaw = JSON.parse(readFileSync(srcPath, 'utf-8'));
const reviews: any[] = srcRaw.reviews ?? srcRaw;
const prodMeta = srcRaw.meta ?? {};
const reviewById = new Map(reviews.map((r: any) => [r.seq, r]));

const esc = (s: unknown) => String(s ?? '').replace(/[&<>"']/g, c => ({ '&': '&amp;', '<': '&lt;', '>': '&gt;', '"': '&quot;', "'": '&#39;' }[c] as string));

// 双语文案表
const I18N = {
    zh: {
        risks: '主要风险', strengths: '主要优点', details: '主题明细（每个结论都引用了原评论）',
        personas: '买家画像', checklist: 'Listing 改写清单（按优先级）', riskBadge: '⚠️ 风险', strengthBadge: '👍 优点',
        times: (n: number) => `出现 ${n} 次`, severity: (n: number) => `严重度 ${n.toFixed(1)}/5`, cause: '归因：', action: '建议：',
        quotes: (n: number) => `引用的原评论 (${n})`, cite: (ok: number, all: number) => `引用可信度：${ok}/${all} 条引用指向真实评论`,
        generated: '生成于 voc-tool', verified: '✓ 已验证购买', unverified: '未验证',
        helpful: (n: number) => `${n} 人觉得有用`, reviews: (c: number, p: number) => `条评论 · 分析 ${c} 条（差评 ${c - p} / 好评 ${p}）`,
        verdict: { 'buy-to-sell': ['✅ 值得入场', 'ok', '评论结构健康，可作为选品参考'], 'improve-first': ['⚠️ 先改后卖', 'warn', '存在可改进的结构性缺陷，入场前先解决'], 'avoid': ['⛔ 建议放弃', 'bad', '差评风险过高，不建议入场'] },
        causeMap: { quality: '质量问题', size_mismatch: '尺寸不符', listing_misleading: '文案误导', packaging: '包装问题', logistics: '物流问题', expectation_gap: '期望落差' },
    },
    en: {
        risks: 'Top Risks', strengths: 'Top Strengths', details: 'Theme Details (every claim cites real reviews)',
        personas: 'Buyer Personas', checklist: 'Listing Rewrite Checklist (by priority)', riskBadge: '⚠️ Risk', strengthBadge: '👍 Strength',
        times: (n: number) => `${n} mentions`, severity: (n: number) => `Severity ${n.toFixed(1)}/5`, cause: 'Cause: ', action: 'Action: ',
        quotes: (n: number) => `Cited reviews (${n})`, cite: (ok: number, all: number) => `Citation integrity: ${ok}/${all} citations point to real reviews`,
        generated: 'Generated by voc-tool', verified: '✓ Verified Purchase', unverified: 'Unverified',
        helpful: (n: number) => `${n} found helpful`, reviews: (c: number, p: number) => `ratings · analyzed ${c} reviews (${c - p} critical / ${p} positive)`,
        verdict: { 'buy-to-sell': ['✅ Buy to Sell', 'ok', 'Healthy review profile, viable product'], 'improve-first': ['⚠️ Improve First', 'warn', 'Fixable structural flaws, address before selling'], 'avoid': ['⛔ Avoid', 'bad', 'High risk profile, not recommended'] },
        causeMap: { quality: 'Quality issue', size_mismatch: 'Size mismatch', listing_misleading: 'Listing mismatch', packaging: 'Packaging', logistics: 'Logistics', expectation_gap: 'Expectation gap' },
    },
} as const;

const cited = (report.themes.zh ?? []).flatMap(t => t.sample_seqs);
const citationOk = cited.filter(s => reviewById.has(s)).length;
const nCrit = reviews.filter((r: any) => r.sentiment === 'critical').length;
const nPos = reviews.length - nCrit;

const themeCard = (t: Theme, L: typeof I18N.zh) => {
    const quotes = t.sample_seqs
        .map(s => reviewById.get(s))
        .filter(Boolean)
        .map((r: any) => `
      <blockquote class="quote">
        <div class="quote-head"><span class="stars">${'★'.repeat(r.rating)}${'☆'.repeat(5 - r.rating)}</span> <span class="qtitle">${esc(r.title)}</span> <span class="qmeta">${r.verified ? L.verified : L.unverified} · ${esc(r.review_date)}${r.helpful ? ` · ${L.helpful(r.helpful)}` : ''}</span></div>
        <div class="qbody">${esc(r.body.slice(0, 400))}${r.body.length > 400 ? '…' : ''}</div>
      </blockquote>`)
        .join('');
    return `
    <div class="card theme ${t.kind}">
      <div class="theme-head">
        <span class="badge ${t.kind}">${t.kind === 'risk' ? L.riskBadge : L.strengthBadge}</span>
        <h3>${esc(t.theme)}</h3>
        <span class="freq">${L.times(t.frequency)}</span>
        ${t.kind === 'risk' ? `<span class="sev">${L.severity(t.severity_avg)}</span>` : ''}
      </div>
      <div class="meta-row">
        <span class="tag">${L.cause}${(L.causeMap as any)[t.root_cause] ?? t.root_cause}</span>
        <span class="tag action">${L.action}${esc(t.listing_action)}</span>
      </div>
      ${quotes ? `<details open><summary>${L.quotes(t.sample_seqs.length)}</summary>${quotes}</details>` : ''}
    </div>`;
};

const pageBody = (lang: 'zh' | 'en') => {
    const L = I18N[lang];
    const R = report.report[lang];
    const themes = report.themes[lang] ?? [];
    const v = (L.verdict as any)[R.verdict] ?? (L.verdict as any)['improve-first'];
    return `
  <header class="hero">
    <div class="lang-toggle">
      <button class="lang-btn ${lang === 'zh' ? 'active' : ''}" data-lang="zh" onclick="setLang('zh')">中</button>
      <button class="lang-btn ${lang === 'en' ? 'active' : ''}" data-lang="en" onclick="setLang('en')">EN</button>
    </div>
    <h1>${esc(prodMeta.title ?? 'Amazon Product')} ${prodMeta.star ? `<span style="font-size:14px;color:#fbbf24">★ ${esc(prodMeta.star)}</span>` : ''}</h1>
    <div class="sub">ASIN ${esc(prodMeta.asin)} · ${prodMeta.reviewCount ?? report.meta.reviewCount} ${L.reviews(reviews.length, nPos)} · ${new Date().toLocaleString('zh-CN')}</div>
    <div><span class="verdict ${v[1]}">${v[0]}</span><span class="verdict-note">${v[2]}</span></div>
  </header>

  <div class="summary">${esc(R.executive_summary)}</div>

  <div class="grid2">
    <div class="card">
      <div class="sec-title" style="margin:0 0 10px"><span class="dot" style="background:var(--red)"></span>${L.risks}</div>
      <div class="pill-list">${R.top_risks.map(r => `<span class="pill risk">${esc(r.theme)}<span class="n">×${r.frequency}</span></span>`).join('')}</div>
    </div>
    <div class="card">
      <div class="sec-title" style="margin:0 0 10px"><span class="dot" style="background:var(--green)"></span>${L.strengths}</div>
      <div class="pill-list">${R.top_strengths.map(r => `<span class="pill strength">${esc(r.theme)}<span class="n">×${r.frequency}</span></span>`).join('')}</div>
    </div>
  </div>

  <div class="sec-title"><span class="dot" style="background:#4f46e5"></span>${L.details}</div>
  ${themes.map(t => themeCard(t, L as any)).join('')}

  <div class="sec-title"><span class="dot" style="background:#0891b2"></span>${L.personas}</div>
  <div class="personas">${R.buyer_personas.map(p => `<span class="persona">👤 ${esc(p)}</span>`).join('')}</div>

  <div class="sec-title"><span class="dot" style="background:#4f46e5"></span>${L.checklist}</div>
  <ol class="checklist">${R.listing_rewrite_checklist.map(c => `<li>${esc(c)}</li>`).join('')}</ol>

  <footer>${L.cite(citationOk, cited.length)} · ${L.generated}</footer>`;
};

